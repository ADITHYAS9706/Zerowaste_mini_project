-- ZeroWasteNet Manager modules
-- Run this script once in Supabase SQL Editor before using Store Community
-- and Redistribution transfer requests.

CREATE TABLE IF NOT EXISTS public.community_offers (
    offer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id TEXT NOT NULL,
    product_id TEXT NOT NULL,
    batch_id TEXT NOT NULL,
    quantity_available INTEGER NOT NULL CHECK (quantity_available >= 0),
    unit_price NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (unit_price >= 0),
    expiry_date DATE NOT NULL,
    pickup_deadline DATE,
    notes TEXT,
    status TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'closed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_community_offers_store_status
    ON public.community_offers (store_id, status);
CREATE INDEX IF NOT EXISTS idx_community_offers_product
    ON public.community_offers (product_id);

CREATE TABLE IF NOT EXISTS public.community_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL REFERENCES public.community_offers(offer_id) ON DELETE CASCADE,
    requesting_store_id TEXT NOT NULL,
    quantity_requested INTEGER NOT NULL CHECK (quantity_requested > 0),
    message TEXT,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_community_requests_offer
    ON public.community_requests (offer_id, status);
CREATE INDEX IF NOT EXISTS idx_community_requests_store
    ON public.community_requests (requesting_store_id, status);

CREATE TABLE IF NOT EXISTS public.redistribution_transfers (
    transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id TEXT NOT NULL,
    from_store TEXT NOT NULL,
    to_store TEXT NOT NULL,
    transfer_quantity INTEGER NOT NULL CHECK (transfer_quantity > 0),
    status TEXT NOT NULL DEFAULT 'requested'
        CHECK (status IN ('requested', 'approved', 'rejected', 'completed')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (from_store <> to_store)
);

CREATE INDEX IF NOT EXISTS idx_redistribution_transfers_status
    ON public.redistribution_transfers (status, created_at DESC);
